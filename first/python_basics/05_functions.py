def clamp(v, lo, hi):
    """[課題2-1] 値 v を lo 以上 hi 以下に収めて返せ．
    v が lo より小さければ lo，hi より大きければ hi，それ以外は v を返す
    (第2週で，ボールが画面からはみ出さないようにするのに使う)"""
    if v <= lo:
        return lo
    if v >= hi:
        return hi
    return v  # TODO
