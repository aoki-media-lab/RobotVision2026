def center(w, h):
    """[課題3-1] 画像の幅 w と高さ h を受け取り，中心の座標 (x, y) を整数のタプルで返せ"""
    return w // 2, h // 2  # TODO


# ============================================================
# セクション4: 関数を引数として渡す
# ============================================================
def apply_all(func, values):
    """values の各要素に func を適用した結果のリストを返す (完成済み)"""
    results = []
    for v in values:
        results.append(func(v))
    return results


def square(x):
    """[課題4-1] x の2乗を返せ"""
