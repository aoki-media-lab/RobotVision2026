"""08 numpy の比較とマスク

実行方法 (first/python_basics で):
    uv run 08_numpy_mask.py

解説は first/README.md の「08 numpy の比較とマスク」を参照．
画像処理の「マスク (どの画素を使うかを表す白黒画像)」は，ここで扱う bool 配列そのもの．
各課題の関数の `...` を書き換えて実行すると，ファイル末尾の main で各課題の結果が表示される．
課題文のとおりの結果になっているかを自分で確かめる．
ある課題で詰まったら，main の中のその課題の行をコメントアウトすれば，他の課題を先に進められる．
"""

import numpy as np



# ============================================================
# セクション1: 比較すると bool 配列になる
# ============================================================
def task_1_1(arr):
    """[課題1-1] arr の要素が 4 より大きいかどうかを表す bool 配列を返せ"""
    return arr > 4


def task_1_2(arr):
    """[課題1-2] arr のうち 4 より大きい要素の個数を返せ (True は 1，False は 0 として足し算できる)"""
    mask = arr > 4
    return mask.sum()


def task_1_3(arr):
    """[課題1-3] bool 配列を添字に使って，arr から 4 より大きい要素だけを取り出して返せ"""
    return arr[arr > 4]


# ============================================================
# セクション2: 範囲の条件 (& と |)
# ============================================================
def task_2_1(hue):
    """[課題2-1] hue が 10 以上 40 以下の要素を True とする bool 配列を返せ
    (cv2.inRange がやっていることと同じ)"""
    return (hue >= 10) & (hue <= 40)


def task_2_2(hue):
    """[課題2-2] 赤色の Hue は 0 付近と 179 付近の両端にまたがる．
    hue が 10 未満 または 170 より大きい要素を True とする bool 配列を返せ"""
    return (hue < 10) | (hue > 170)


# ============================================================
# セクション3: np.where で値を置き換える (二値化)
# ============================================================
def task_3_1():
    """[課題3-1] gray を「128 以上なら 255，それ以外は 0」に二値化して返せ．
    画像として扱えるよう，dtype は np.uint8 にすること"""
    gray = np.array([[10, 200, 130], [90, 250, 40]], dtype=np.uint8)
    return np.where(gray >= 128, 255, 0).astype(np.uint8)


# ============================================================
# セクション4: 白い領域を囲む四角形
# ============================================================
def task_4_1():
    """[課題4-1] binary の白い (255 の) 領域を囲む四角形の (左, 上, 右, 下) を返せ．
    np.where(条件) で白い画素の (行の添字の配列, 列の添字の配列) を取り出して使う"""
    binary = np.zeros((6, 8), dtype=np.uint8)
    binary[2:5, 3:7] = 255  # 2〜4 行目，3〜6 列目 が白
    idy, idx = np.where(binary == 255)
    print(idx,idy)
    return min(idx),min(idy),max(idx),max(idy)


# ============================================================
# セクション5: バグ修正
# ============================================================
def task_5_1(arr):
    """[バグ修正5-1] arr に 4 より大きい要素が1つでもあれば "大きい値がある"，なければ "ない" を返したいが，
    エラーになる．エラーメッセージが勧めている方法のどちらを使えばよいか考えて直せ"""
    if np.any(arr > 4):
        return "大きい値がある"
    else:
        return "ない"


if __name__ == "__main__":
    arr = np.array([3, 8, 1, 9, 5])
    hue = np.array([5, 20, 35, 90, 110, 175])
    print("課題1-1:", task_1_1(arr))
    print("課題1-2:", task_1_2(arr))
    print("課題1-3:", task_1_3(arr))
    print("課題2-1:", task_2_1(hue))
    print("課題2-2:", task_2_2(hue))
    print("課題3-1:", task_3_1())
    print("課題4-1:", task_4_1())
    print("課題5-1:", task_5_1(arr))
