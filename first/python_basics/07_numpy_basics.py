import numpy as np


# ============================================================
# セクション1: 配列の作成と形状
# ============================================================
def task_1_1():
    """[課題1-1] np.array を使って 1行目が 1, 2, 3，2行目が 4, 5, 6 の 2行3列 の配列を作って返せ"""
    return np.array([[1, 2, 3], [4, 5, 6]])


def task_1_2(arr):
    """[課題1-2] 配列 arr の形状 (shape) を返せ"""
    return arr.shape


def task_1_3():
    """[課題1-3] np.arange を使って 0, 5, 10, 15 の配列を作って返せ"""
    return np.arange(0, 16, 5)  # TODO


# ============================================================
# セクション2: 要素の取り出し
# ============================================================
def task_2_1(arr_2d):
    """[課題2-1] arr_2d の 1 列目 (2, 5, 8, 11) をまとめて取り出して返せ"""
    return arr_2d[:, 1]  # TODO


def task_2_2(arr_2d):
    """[課題2-2] arr_2d の 1〜2 行目，0〜1 列目 の部分を取り出して返せ (画像の切り出しと同じ操作)"""
    return arr_2d[1:3, 0:2]  # TODO


# ============================================================
# セクション3: 配列の計算
# ============================================================
def task_3_1():
    """[課題3-1] a と b の要素ごとの差 (b - a) を返せ"""
    a = np.array([1, 2, 3])
    b = np.array([4, 5, 6])
    return b - a


def task_3_2(arr_2d):
    """[課題3-2] arr_2d の全要素の平均と最大値を (平均, 最大値) のタプルで返せ (np.mean, np.max)"""
    return np.mean(arr_2d), np.max(arr_2d)


# ============================================================
# セクション4: ブロードキャスト
# ============================================================
def task_4_1():
    """[課題4-1] 2x2 画素のカラー画像 img (高さ, 幅, チャンネル) = (2, 2, 3) の全画素について，
    B を +50，G を +0，R を -50 した配列を，ブロードキャストを使って作って返せ．
    チャンネルは B, G, R の順"""
    img = np.full((2, 2, 3), 100)
    return img + np.array([50, 0, -50])


# ============================================================
# セクション5: 乱数とソート
# ============================================================
def make_values():
    """0〜1 の乱数を 100 個作る (種を 0 に固定しているので毎回同じ値になる)"""
    rng = np.random.default_rng(0)
    return rng.random(100)


def task_5_1(values):
    """[課題5-1] values の 11〜20 番目 (先頭を1番目と数える) の 10 個をスライスで取り出して返せ"""
    return values[10:20]

def task_5_2(values):
    """[課題5-2] values を大きい順 (降順) に並べた配列を返せ．np.sort は小さい順に並べる"""
    return np.sort(values)[::-1]


# ============================================================
# セクション6: バグ修正
# ============================================================
def task_6_1():
    """[バグ修正6-1] (2, 3) の行列 m1 と (2, 3) の行列 m2 の積 m1・m2^T (結果は (2, 2)) を返したいが，
    エラーになる．エラーメッセージの shape の情報を読んで直せ"""
    m1 = np.array([[1, 2, 3], [4, 5, 6]])
    m2 = np.array([[4, 5, 6], [1, 2, 3]])
    return np.dot(m1, m2.T)


